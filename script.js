/* ============ TOAST ============ */
const toast = document.getElementById('toast');
let toastTimer;
function showToast(msg, success=false){
  toast.textContent = msg;
  toast.classList.toggle('success', success);
  toast.classList.add('show');
  clearTimeout(toastTimer);
  toastTimer = setTimeout(()=> toast.classList.remove('show'), 3500);
}

/* ============ FORM → WHATSAPP ============ */
const form = document.getElementById('leadForm');
form.addEventListener('submit', (e)=>{
  e.preventDefault();
  const dict = translations[currentLang];
  const labels = I18N_LABELS[currentLang];

  const data = new FormData(form);
  const name = (data.get('name')||'').toString().trim();
  const phoneRaw = (data.get('phone')||'').toString().trim();
  const service = (data.get('service')||'').toString().trim();
  const message = (data.get('message')||'').toString().trim();
  const recipient = (data.get('recipient')||'77754492929').toString();

  // Validation
  const phoneDigits = phoneRaw.replace(/\D/g,'');
  if(name.length < 2 || phoneDigits.length < 10 || !service){
    showToast(dict["form.toast.err"]);
    if(name.length < 2) form.name.focus();
    else if(phoneDigits.length < 10) form.phone.focus();
    else form.service.focus();
    return;
  }

  // Build WhatsApp message
  const lines = [
    dict["form.wa.greet"],
    "",
    `👤 ${labels.name}: ${name}`,
    `📞 ${labels.phone}: ${phoneRaw}`,
    `💼 ${labels.service}: ${service}`,
  ];
  if(message) lines.push(`💬 ${labels.message}: ${message}`);

  const text = encodeURIComponent(lines.join('\n'));
  const url = `https://wa.me/${recipient}?text=${text}`;

  showToast(dict["form.toast.ok"], true);
  // open in new tab
  window.open(url, '_blank', 'noopener');
});

